def apply_plan(root: Path, plan: Plan, *, force: bool = False) -> None:
    if not force:
        conflicts = protected_write_conflicts(root, plan)
        if conflicts:
            lines = [
                "REFUSING overwrite of hand-written file(s) without GEN_MARK provenance:",
                *[f"  {c}" for c in conflicts],
                "Re-run with --force to overwrite, or rename/remove the hand-written file.",
            ]
            raise SystemExit("\n".join(lines))
    for rel, content in sorted(plan.writes.items()):
        p = root / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(content, encoding="utf-8")
    for rel in plan.deletes:
        p = root / rel
        if p.is_file():
            p.unlink()
            # remove empty skill dirs
            parent = p.parent
            while parent != root and parent.is_dir() and not any(parent.iterdir()):
                parent.rmdir()
                parent = parent.parent


# ── config / cli ─────────────────────────────────────────────────────────────


def load_config(root: Path, explicit: str | None) -> dict:
    cfg = dict(DEFAULT_CONFIG)
    path = root / (explicit or ".mdc-convert.json")
    if path.is_file():
        try:
            user = json.loads(path.read_text(encoding="utf-8"))
        except json.JSONDecodeError as exc:
            raise SystemExit(f"{path}: invalid JSON: {exc}")
        for k, v in user.items():
            if k.startswith("_"):
                continue
            if k not in DEFAULT_CONFIG:
                raise SystemExit(f"{path}: unknown key '{k}'")
            cfg[k] = v
    return cfg


def summarize(plan: Plan, root: Path) -> str:
    lines = [f"mdc_convert {VERSION} — root {root}"]
    if not plan.rules:
        lines.append("no .mdc sources found (looked in .cursor/rules/**, nested .cursor/rules, .cursorrules)")
    for r in plan.rules:
        lines.append(f"  {r.source:45s} {r.cursor_type:7s} → {r.target:6s} {r.out_path}")
    for n in plan.notes:
        lines.append(f"  note: {n}")
    for rel in sorted(plan.writes):
        lines.append(f"  write  {rel}")
    for rel in plan.deletes:
        lines.append(f"  delete {rel}")
    if not plan.writes and not plan.deletes:
        lines.append("  outputs up to date")
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0], formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--root", default=".", help="repo root (default: cwd)")
    ap.add_argument("--config", default=None, help="config JSON (default: .mdc-convert.json if present)")
    ap.add_argument("--src", action="append", default=[], metavar="DIR",
                    help="extra .mdc source dir (repeatable; e.g. ../.cursor/rules for a shared apps/ folder)")
    ap.add_argument("--check", action="store_true", help="exit 1 if outputs are stale (CI gate); writes nothing")
    ap.add_argument("--dry-run", action="store_true", help="print the plan; write nothing")
    ap.add_argument("--force", action="store_true",
                    help="overwrite hand-written .claude/rules or skills that lack GEN_MARK provenance")
    ap.add_argument("--json", action="store_true", help="print the plan as JSON")
    ap.add_argument("--version", action="version", version=VERSION)
    ns = ap.parse_args(argv)

    root = Path(ns.root).resolve()
    if not root.is_dir():
        print(f"error: root {root} is not a directory", file=sys.stderr)
        return 2
    cfg = load_config(root, ns.config)
    if ns.src:
        cfg["sources"] = list(cfg["sources"]) + list(ns.src)
    plan = build_plan(root, cfg)
    conflicts = [] if ns.force else protected_write_conflicts(root, plan)

    if ns.json:
        print(json.dumps({
            "rules": [r.__dict__ for r in plan.rules],
            "writes": sorted(plan.writes),
            "deletes": plan.deletes,
            "notes": plan.notes,
            "conflicts": conflicts,
        }, indent=2, sort_keys=True, default=str))
    else:
        print(summarize(plan, root))
        for c in conflicts:
            print(f"  conflict  {c} (hand-written; needs --force)")

    if conflicts and not ns.dry_run:
        # --check and normal apply both refuse; dry-run only reports
        print(
            "CONFLICT: refusing overwrite of hand-written file(s) without GEN_MARK. "
            "Use --force to overwrite, or rename/remove the hand-written file.",
            file=sys.stderr,
        )
        return 1
    if ns.check:
        if plan.writes or plan.deletes:
            print("STALE: run `python3 scripts/mdc_convert.py` and commit the outputs", file=sys.stderr)
            return 1
        print("OK mdc_convert --check")
        return 0
    if ns.dry_run:
        return 0
    apply_plan(root, plan, force=ns.force)
    print(f"OK mdc_convert ({len(plan.writes)} written, {len(plan.deletes)} pruned)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
